if __name__ == "__main__":

    engineer = FeatureEngineer(processed_dir='data/processed')

    tickers = ['SPY', 'AAPL', 'BTC-USD']

    print("\n" + "="*60)
    print("FEATURE ENGINEERING PIPELINE")
    print("="*60)

    for ticker in tickers:
        df = engineer.create_all_features(ticker)
        engineer.get_feature_summary(df)

    print(f"\n{'='*60}")
    print("✓ Feature engineering complete!")
    print(f"{'='*60}\n")