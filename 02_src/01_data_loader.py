def run_pipeline():
    """Run the data pipeline."""
    print("\n" + "="*60)
    print("STARTING DATA DOWNLOAD PIPELINE")
    print("="*60 + "\n")
    sys.stdout.flush()

    # Initialize loader
    loader = DataLoader(data_dir='data')

    # Define parameters
    tickers = ['SPY', 'AAPL', 'BTC-USD']
    end_date = datetime.now().strftime('%Y-%m-%d')
    start_date = (datetime.now() - timedelta(days=5*365)).strftime('%Y-%m-%d')

    print(f"Start date: {start_date}")
    print(f"End date: {end_date}")
    print(f"Tickers: {tickers}\n")
    sys.stdout.flush()

    # Download, process, and save
    processed_data = loader.prepare_full_dataset(tickers, start_date, end_date)

    # Print summaries
    for ticker, df in processed_data.items():
        loader.summary(df, ticker)

    print(f"\n{'='*60}")
    print("✓ Data pipeline complete!")
    print(f"Raw data saved to: {loader.raw_dir}")
    print(f"Processed data saved to: {loader.processed_dir}")
    print(f"{'='*60}\n")
    sys.stdout.flush()

    return processed_data

if __name__ == "__main__":
    run_pipeline()