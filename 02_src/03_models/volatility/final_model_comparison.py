import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from pathlib import Path
import warnings

warnings.filterwarnings('ignore')

results_dir = Path('results')

print("\n" + "="*80)
print("FINAL MODEL COMPARISON: GARCH vs EWMA vs XGBoost vs LightGBM")
print("="*80 + "\n")

tickers = ['SPY', 'AAPL', 'BTC-USD']
model_types = ['garch', 'ewma', 'xgboost', 'lightgbm']

all_results = []

for ticker in tickers:
    print(f"\n{ticker}:")
    print("-" * 80)

    ticker_results = {'Ticker': ticker}

    for model_type in model_types:
        forecast_path = results_dir / f"{ticker}_{model_type}_forecast.csv"

        if not forecast_path.exists():
            print(f"  {model_type.upper()}: File not found")
            continue

        df = pd.read_csv(forecast_path, index_col=0, parse_dates=True).dropna()

        if len(df) == 0:
            print(f"  {model_type.upper()}: No valid data")
            continue

        actual = df['test_actual'].values
        forecast = df['test_forecast'].values

        mae = np.mean(np.abs(actual - forecast))
        rmse = np.sqrt(np.mean((actual - forecast)**2))
        mape = np.mean(np.abs((actual - forecast) / actual)) * 100

        try:
            corr = np.corrcoef(actual, forecast)[0, 1]
        except:
            corr = 0.0

        actual_direction = np.diff(actual) > 0
        forecast_direction = np.diff(forecast) > 0
        dir_acc = np.mean(actual_direction == forecast_direction) * 100

        ticker_results[f'{model_type.upper()}_MAE'] = mae
        ticker_results[f'{model_type.upper()}_RMSE'] = rmse
        ticker_results[f'{model_type.upper()}_Corr'] = corr

        print(f"  {model_type.upper():10s} - MAE: {mae:.4f}  RMSE: {rmse:.4f}  Corr: {corr:7.4f}  Dir%: {dir_acc:5.1f}%")

    all_results.append(ticker_results)

results_df = pd.DataFrame(all_results)

print("\n" + "="*80)
print("SUMMARY TABLE - MAE (Lower is Better)")
print("="*80 + "\n")

summary_mae = results_df[['Ticker', 'GARCH_MAE', 'EWMA_MAE', 'XGBOOST_MAE', 'LIGHTGBM_MAE']]
print(summary_mae.to_string(index=False))

print("\n" + "="*80)
print("SUMMARY TABLE - Correlation (Higher is Better)")
print("="*80 + "\n")

summary_corr = results_df[['Ticker', 'GARCH_Corr', 'EWMA_Corr', 'XGBOOST_Corr', 'LIGHTGBM_Corr']]
print(summary_corr.to_string(index=False))

fig, axes = plt.subplots(3, 2, figsize=(16, 12))
fig.suptitle('Model Comparison: All 4 Methods', fontsize=16, fontweight='bold')

for idx, ticker in enumerate(tickers):
    print(f"\nGenerating plots for {ticker}...")

    ax_ts = axes[idx, 0]
    ax_box = axes[idx, 1]

    models_data = {}

    for model_type in model_types:
        forecast_path = results_dir / f"{ticker}_{model_type}_forecast.csv"

        if forecast_path.exists():
            df = pd.read_csv(forecast_path, index_col=0, parse_dates=True).dropna()
            if len(df) > 0:
                models_data[model_type] = df

    if models_data:
        ax_ts.set_title(f'{ticker} - Time Series Forecasts', fontweight='bold')

        first_df = list(models_data.values())[0]
        actual = first_df['test_actual']
        ax_ts.plot(actual.index, actual.values, label='Actual', linewidth=2.5, color='black', alpha=0.8)

        colors = {'garch': 'red', 'ewma': 'blue', 'xgboost': 'green', 'lightgbm': 'orange'}
        for model_type, df in models_data.items():
            ax_ts.plot(df.index, df['test_forecast'].values, label=model_type.upper(),
                      linewidth=1.5, alpha=0.7, color=colors[model_type])

        ax_ts.set_ylabel('Volatility')
        ax_ts.legend(loc='best')
        ax_ts.grid(True, alpha=0.3)

        ax_box.set_title(f'{ticker} - Error Distribution', fontweight='bold')

        errors = {}
        for model_type, df in models_data.items():
            actual = df['test_actual'].values
            forecast = df['test_forecast'].values
            errors[model_type.upper()] = np.abs(actual - forecast)

        error_df = pd.DataFrame(errors)
        error_df.boxplot(ax=ax_box)
        ax_box.set_ylabel('Absolute Error')
        ax_box.grid(True, alpha=0.3, axis='y')

plt.tight_layout()
plt.savefig('results/all_models_comparison.png', dpi=150, bbox_inches='tight')
print("\n✓ Saved comparison plot to results/all_models_comparison.png")
plt.show()

